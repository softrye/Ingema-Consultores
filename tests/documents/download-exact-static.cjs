const fs=require('node:fs'),assert=require('node:assert/strict');
const source=fs.readFileSync('src/documents/nothingdocuments.cpp','utf8');
const cloud=fs.readFileSync('clouddocs.cpp','utf8');
const download=source.slice(source.indexOf('void NothingDocuments::download('),source.indexOf('void NothingDocuments::upload('));
assert.ok(download.includes('m_cloud->downloadExact(access.value("bucket").toString(),'),'download must use the server bucket, not global IngePlus');
assert.ok(!download.includes('m_cloud->downloadJson('));
assert.ok(download.includes('access.value("size_bytes").toLongLong()'));
assert.ok(download.includes('if(epoch!=m_epoch) return;'),'old-account responses cannot populate a new mirror');
const exact=cloud.slice(cloud.indexOf('void CloudDocs::downloadExact('),cloud.indexOf('void CloudDocs::downloadObject('));
assert.ok(exact.includes('bucket != "project-files"'));
assert.ok(!exact.includes('m_bucket ='),'never mutate shared legacy configuration');
const object=cloud.slice(cloud.indexOf('void CloudDocs::downloadObject('),cloud.indexOf('QString CloudDocs::inferRelativePathFromLocalPath('));
assert.ok(object.includes('bucket + "/"'),'exact bucket flows into HTTP URL');
assert.ok(object.includes('m_auth->accessToken()'));
assert.ok(object.includes('QSaveFile f(savePath)') && object.includes('f.commit()'),'partial response must not overwrite a valid mirror');
assert.ok(object.includes('raw.size() != expectedSize'),'truncated payload cannot be marked downloaded');
assert.ok(object.includes('epoch != m_accountEpoch'));
assert.ok(object.includes('reply->abort()'),'network request has a bound');
console.log('PASS download: exact bucket/path, session guard, atomic save, byte count and timeout');
