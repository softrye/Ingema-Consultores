"use strict";
const fs = require("fs"), vm = require("vm"), assert = require("assert"), path = require("path");
const rules = vm.createContext({});
vm.runInContext(fs.readFileSync(path.resolve(__dirname, "../../qml/Mobile/lib/CalicataRules.js"), "utf8").replace(/^\s*\.pragma.*$/mg, ""), rules);
const plain = x => JSON.parse(JSON.stringify(x));
const sample = (fines, ll=30, lp=20) => ({passing4:90, passing10:70, passing40:30, passing200:fines, liquidLimit:ll, plasticLimit:lp});
assert.ok(Math.abs(rules.sucsDiameterAt([{diameter:1, passing:10},{diameter:10, passing:60}], 35)-Math.sqrt(10))<1e-12);
assert.strictEqual(rules.sucsDiameterAt([{diameter:1, passing:20},{diameter:10, passing:60}], 10), null, "Never extrapolate D10");
assert.strictEqual(rules.sucsGradation("G", {d10:1,d30:2,d60:4}), "GW");
assert.strictEqual(rules.sucsGradation("S", {d10:1,d30:Math.sqrt(6),d60:6}), "SW");
assert.strictEqual(rules.sucsGradation("S", {d10:1,d30:1.5,d60:5}), "SP");
assert.strictEqual(rules.sucsGradation("S", {d10:1,d30:null,d60:6}), null);
assert.deepStrictEqual(plain(rules.recommendSucs(sample(10)).candidates), ["SW-SC"]);
assert.deepStrictEqual(plain(rules.recommendSucs(sample(12)).candidates), ["SW-SC","SP-SC"]);
assert.deepStrictEqual(plain(rules.recommendSucs(sample(12.01)).candidates), ["SC"]);
assert.deepStrictEqual(plain(rules.recommendSucs(sample(15,25,20)).candidates), ["SC-SM"]);
assert.deepStrictEqual(plain(rules.recommendSucs({...sample(60,25,20),passing10:80,passing40:65}).candidates), ["CL-ML"]);
assert.deepStrictEqual(plain(rules.recommendSucs(sample(15,30,19)).candidates), ["SC"]);
assert.ok(rules.recommendSucs(sample(5)).candidates.every(c=>c.includes("-")), "5 percent fines already requires dual symbols");
assert.ok(rules.recommendSucs(sample(4.99)).candidates.every(c=>!c.includes("-")), "Below 5 percent is clean coarse soil");
assert.strictEqual(rules.recommendSucs({...sample(60,120,47),passing10:80,passing40:65}).candidates[0], "CH", "On the A line belongs to the clay side");
assert.strictEqual(rules.recommendSucs(sample(15,20,30)), null, "Reject negative PI");
assert.strictEqual(rules.recommendSucs({...sample(15),passing4:10}), null, "Reject nonmonotone sieves");
const missing=rules.recommendSucs({...sample(10),passing4:null}); assert.strictEqual(missing.conclusive,false);
assert.deepStrictEqual(plain(rules.sucsSelection("SW-SC")), {primary:"SW", secondary:"SC", isComposite:true});
assert.strictEqual(rules.sucsSelection("GW-SC"),null);
const selected={primarySucs:"SW",secondarySucs:"SC",isComposite:true};
assert.strictEqual(rules.labSuggestion(selected,{sucs:{candidates:["SW-SC"],conclusive:true,reason:""}}).sucs[0].current,true);
const report=rules.reviewLaboratorySample({...selected,sieveMaxPct:"100",sieveNo4Pct:"90",sieve2mmPct:"70",sieve04mmPct:"30",sieve008mmPct:"10",liquidLimit:"30",plasticLimit:"20"});
assert.ok(!report.observations.some(o=>o.id==="sucs-mismatch"),"Adopted dual classification must match recommendation");
assert.strictEqual(rules.resolveCalicataSucsPattern("SW",true,"SC").layers.length,2);
console.log("SUCS: interpolation, Cu/Cc, boundary cases, dual adoption and pattern projection passed");
