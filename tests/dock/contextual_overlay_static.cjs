'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const home = fs.readFileSync(path.resolve(__dirname, '../../qml/Mobile/HomeScreen.qml'), 'utf8').replace(/\r\n/g, '\n');
const glass = fs.readFileSync(path.resolve(__dirname, '../../qml/Mobile/DockGlassPanel.qml'), 'utf8').replace(/\r\n/g, '\n');
const calicata = fs.readFileSync(path.resolve(__dirname, '../../qml/Mobile/pages/CalicataFormPage.qml'), 'utf8').replace(/\r\n/g, '\n');
const start = home.indexOf('// Dock contextual = superposición');
const quickBubble = home.indexOf('// Quick Bubble:', start);
assert.ok(start > 0 && quickBubble > start, 'contextual overlay and menu anchors are present');
const overlay = home.slice(start, quickBubble);
assert.doesNotMatch(overlay, /Rectangle\s*\{|color:\s*"#0A1020"|opacity:\s*0\.30/);
assert.match(overlay, /MouseArea\s*\{/);
assert.match(overlay, /visible:\s*dockMenuBox\.open/);
assert.match(overlay, /onClicked:\s*home\.dockPath\s*=\s*\[\]/);
assert.match(home, /readonly property Item dockBackdropSource:[^\n]+homeContent/);
assert.match(home, /page === "calicatas" && calicatasEditor\.status === Loader\.Ready \? calicatasEditor/);
assert.match(home, /page === "rendiciones" && renditionsLoader\.status === Loader\.Ready \? renditionsLoader/);
assert.match(home, /sourceItem:\s*home\.dockBackdropSource/);
assert.match(home, /hideSource:\s*false/);
assert.match(home, /DockGlassPanel \{ id: dockLiquidGlass; glassUi: home\.dockGlassUi/);
assert.match(glass, /GlassSurface\s*\{/);
assert.match(home, /id:\s*dock\n[\s\S]*?color:\s*"transparent"/);
// Calicata form must render underneath the capsule and keep the last controls scrollable.
const vFlick = calicata.slice(calicata.indexOf('id: vFlick'), calicata.indexOf('id: documentStateBridge'));
assert.match(vFlick, /anchors\.bottomMargin:\s*0/);
assert.match(vFlick, /contentHeight:\s*finalPageCol\.implicitHeight \+ root\.dp\(24\) \+ root\.fichaDockClearance/);
assert.doesNotMatch(vFlick, /anchors\.bottomMargin:\s*root\.fichaDockClearance/);
assert.match(calicata, /readonly property real fichaDockClearance:/);
console.log('PASS: contextual Dock overlays the calling page without full-screen scrim; Calicatas scrolls under Dock with safe end padding');
